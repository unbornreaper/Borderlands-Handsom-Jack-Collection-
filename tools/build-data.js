#!/usr/bin/env node
/*
 * Builds data/bl2.js and data/tps.js from Gibbed's game dumps.
 *
 *   git clone https://github.com/gibbed/Borderlands2Dumps
 *   git clone https://github.com/gibbed/BorderlandsOzDumps
 *   git clone https://github.com/apocalyptech/borderlands2   (challenge list)
 *   node tools/build-data.js <Borderlands2Dumps> <BorderlandsOzDumps> <apocalyptech-borderlands2>
 */
const fs = require('fs');
const path = require('path');

const [bl2Dir, tpsDir, pyDir] = process.argv.slice(2);
if (!bl2Dir || !tpsDir || !pyDir) {
  console.error('usage: node tools/build-data.js <Borderlands2Dumps> <BorderlandsOzDumps> <apocalyptech-borderlands2>');
  process.exit(1);
}

const read = (dir, name) => {
  const p = path.join(dir, name + '.json');
  if (!fs.existsSync(p)) return {};
  let txt = fs.readFileSync(p, 'utf8').replace(/^﻿/, '');
  return JSON.parse(txt);
};

// Parse the challenge list out of the python data file as plain text (no code is run).
function parseChallenges(file) {
  const src = fs.readFileSync(file, 'utf8');
  const cats = {};
  for (const m of src.matchAll(/(\w+)\s*=\s*ChallengeCategory\("([^"]+)"(?:,\s*(\d+))?/g)) cats[m[1]] = { name: m[2], dlc: m[3] ? +m[3] : 0 };
  const out = [];
  const re = /challenges\[(\d+)\]\s*=\s*Challenge\(([\s\S]*?)\n\s*\)/g;
  for (const m of src.matchAll(re)) {
    const body = m[2];
    const g = (k) => { const r = body.match(new RegExp(k + '\\s*=\\s*("(?:[^"\\\\]|\\\\.)*"|\\([^)]*\\)|[\\w.]+)')); return r ? r[1] : null; };
    const str = (s) => s ? JSON.parse(s) : '';
    const levels = (g('levels') || '()').replace(/[()\s]/g, '').split(',').filter(Boolean).map(Number);
    out.push({
      id: +m[1],
      cat: (cats[g('category')] || {}).name || 'Other',
      name: str(g('name')),
      desc: str(g('description')),
      levels,
      bonus: g('bonus') && g('bonus') !== 'None' ? +g('bonus') : null,
    });
  }
  return out;
}

function compactALM(alm) {
  // sets[id][group] = [[package, [asset,...]], ...]
  const sets = {};
  for (const s of alm.sets) {
    sets[s.id] = {};
    for (const [g, lib] of Object.entries(s.libraries)) sets[s.id][g] = lib.sublibraries.map((sl) => [sl.package, sl.assets]);
  }
  return { version: alm.version, sets };
}

function build(dir, challengeFile, key, title) {
  const data = {
    key,
    title,
    alm: compactALM(read(dir, 'Asset Library Manager')),
    classes: read(dir, 'Player Classes'),
    weaponTypes: read(dir, 'Weapon Types'),
    weaponBalance: read(dir, 'Weapon Balance'),
    weaponBalanceParts: read(dir, 'Weapon Balance Part Lists'),
    weaponPartLists: read(dir, 'Weapon Part Lists'),
    weaponParts: read(dir, 'Weapon Parts'),
    weaponNames: read(dir, 'Weapon Name Parts'),
    items: read(dir, 'Items'),
    itemBalance: read(dir, 'Item Balance'),
    itemBalanceParts: read(dir, 'Item Balance Part Lists'),
    itemPartLists: read(dir, 'Item Part Lists'),
    itemParts: read(dir, 'Item Parts'),
    itemNames: read(dir, 'Item Name Parts'),
    customizations: read(dir, 'Customizations'),
    travel: read(dir, 'Travel Stations'),
    travelOrder: read(dir, 'Fast Travel Station Ordering'),
    missions: read(dir, 'Missions'),
    dlc: read(dir, 'Downloadable Packages'),
    dlcContents: read(dir, 'Downloadable Contents'),
    skills: read(dir, 'Skills'),
    challenges: parseChallenges(challengeFile),
  };
  const out = path.join(__dirname, '..', 'data', key + '.js');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, '/* Generated by tools/build-data.js from Gibbed\'s dumps. Do not edit. */\n' +
    '(window.WB_DATA = window.WB_DATA || {})[' + JSON.stringify(key) + '] = ' + JSON.stringify(data) + ';\n');
  console.log(out, (fs.statSync(out).size / 1024).toFixed(0) + ' KB', 'challenges:', data.challenges.length);
}

build(bl2Dir, path.join(pyDir, 'borderlands', 'bl2_data.py'), 'bl2', 'Borderlands 2');
build(tpsDir, path.join(pyDir, 'borderlands', 'bltps_data.py'), 'tps', 'Borderlands: The Pre-Sequel');
